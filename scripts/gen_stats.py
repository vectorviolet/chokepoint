OUT = ROOT / "docs" / "stats"
REPO = "https://github.com/vectorviolet/chokepoint"
PLANE_TYPE = 4
# Endless waves listed after the last authored one, as a sample of the pattern.
ENDLESS_SAMPLE = 10
# config/enemies.yaml has no names, only comments; these are the README's roles.
ENEMY_NAMES = {
    1: "Grunt",
    2: "Fast runner",
    3: "Bruiser",
    4: "Heavy",
    5: "Tank",
    6: "Siege tank",
}

# Page file in docs/stats/ -> page name in the wiki.
PAGES = {
    "README.md": "Stats",
    "towers.md": "Stats-Towers",
    "enemies.md": "Stats-Enemies",
    "waves.md": "Stats-Waves",
}

Link = Callable[[str], str]


def docs_link(page: str) -> str:
    return page


def wiki_link(page: str) -> str:
    return PAGES[page]


# ── formatting ───────────────────────────────────────────────────────────────


def money(n: int) -> str:
    return f"${n:,}"


def num(x: float, places: int = 1) -> str:
    return f"{x:,.{places}f}"


def tiles(px: float) -> str:
    return f"{px:g} ({px / TILE_SIZE:g} tiles)"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def enemy_name(enemy_type: int) -> str:
    return ENEMY_NAMES.get(enemy_type, f"Enemy {enemy_type}")


def header(title: str, link: Link | None) -> list[str]:
    """A page's title and generated-file note; `link` adds a link back to
    the index (None on the index itself)."""
    back = "" if link is None else f" [Back to the index]({link('README.md')})."
    return [
        f"# {title}",
        "",
        "<!-- Generated by scripts/gen_stats.py from config/*.yaml; "
        "don't edit by hand. -->",
        "",
        f"Generated from the game's config by [`scripts/gen_stats.py`]"
        f"({REPO}/blob/main/scripts/gen_stats.py); don't edit it by hand.{back}",
        "",
    ]


# ── what the game does ───────────────────────────────────────────────────────


def scaled_enemy(enemy_type: int, wave: int) -> tuple[int, int]:
    """(max HP, kill money) of an enemy spawned in `wave`, by the game's code."""
    enemy = Enemy.__new__(Enemy)
    enemy._calculate_stats(enemy_type, wave)
    return enemy.maxHP, enemy.killMoney


def all_waves(last: int) -> dict[int, tuple[list[tuple[int, int]], int, bool]]:
    """Wave -> (groups, spawn interval in ms, authored?) for waves 1..last,
    as the wave manager builds them."""
    authored = load_wave_compositions()
    manager = WaveManager([Vector2()], None)
    waves = {}
    for wave in range(1, last + 1):
        wave_def = authored.get(wave) or manager._wave_for(wave)
        waves[wave] = (
            list(wave_def.groups),
            manager._interval_of(wave_def),
            wave in authored,
        )
    return waves


def starting_values() -> tuple[int, int]:
    with open(ROOT / "config" / "settings.yaml", encoding="utf-8") as f:
        gameplay = yaml.safe_load(f)["gameplay"]
    return gameplay["starting_money"], gameplay["starting_lives"]


