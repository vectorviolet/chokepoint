"""Build the stats reference in docs/stats/ from the game's config (issue #82).

    uv run python scripts/gen_stats.py                 # rewrite docs/stats/
    uv run python scripts/gen_stats.py --check         # exit 1 if a page is out of date
    uv run python scripts/gen_stats.py --wiki <dir>    # write the wiki copies into <dir>

Every number comes from config/towers.yaml, config/enemies.yaml and
config/waves.yaml through util.config_loader, and the per-wave figures come
from the game's own code: enemy HP and kill money from Enemy._calculate_stats,
the endless waves after the last authored one from WaveManager._wave_for, so
the pages show what the game does, not a copy of its formulas.
tests/test_stats_docs.py runs the check in CI. .github/workflows/wiki.yml
mirrors the pages to the GitHub wiki with --wiki, which renames them
(README.md -> Stats.md, towers.md -> Stats-Towers.md, ...) and rewrites the
links between them.

Never edit docs/stats/ by hand: change the config and run this script.
"""

